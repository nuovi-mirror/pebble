void cli
(Args *args)
{
	if (args->count <= 0 || args->values[0] == NULL || args->values[0] == NULL) 
	{
		print("ERROR: CLI: NO ARGUMENTS PROVIDED!\n");
		exitproc(1);
	}

	if (cmpstr(args->values[1], "logo") == 0) {
		print(logo);
		exitproc(0);
	} else if (cmpstr(args->values[1], "help") == 0) {
		print(help);
		exitproc(0);
	}
}

