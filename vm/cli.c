#include "exitproc.h"
#include "cmpstr.h"
#include "cli.h"

void pnexit
(const char *msg)
{
	print(msg);
	exitproc(0);
}

void cli
(Args *args)
{
	if (args->count > 2) return;
	if (cmpstr(args->values[1], "logo") == 0) pnexit(logo);
	else if (cmpstr(args->values[1], "help") == 0) pnexit(help);
	else if (cmpstr(args->values[1], "version") == 0) pnexit(version);

	else if (cmpstr(args->values[1], "--help") == 0) pnexit(help);
	else if (cmpstr(args->values[1], "--version") == 0) pnexit(version);
}

